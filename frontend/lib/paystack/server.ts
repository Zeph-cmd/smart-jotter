/**
 * Builds a service-role Supabase client that bypasses RLS. Used to update
 * entitlements after a verified payment. This mirrors the pattern in the
 * signup route.
 */
export function createServiceRoleSupabaseClient() {
  return createClient(getSupabaseUrl(), getSupabaseServiceRoleKey(), {
    // Smart Jotter tables live in the dedicated "jotter" schema of the shared
    // Supabase project (see lib/supabase/browser.ts).
    db: { schema: "jotter" },
    auth: { autoRefreshToken: false, persistSession: false }
  });
}

/* -------------------------------------------------------------------------- */
/* Reference validation (injection / SSRF defense)                             */
/* -------------------------------------------------------------------------- */

/**
 * Paystack transaction references are generated by us (see the client helper)
 * and are alphanumeric with dashes/underscores only. We validate the format
 * before placing the reference into the verify URL to prevent path traversal,
 * CRLF injection, or SSRF-style payloads from reaching the outbound request.
 *
 * References we generate look like: sj_stt_stt240_1699999999_abc123
 */
const PAYSTACK_REFERENCE_RE = /^[A-Za-z0-9_-]{4,120}$/;

export function isValidPaystackReference(reference: string): boolean {
  return PAYSTACK_REFERENCE_RE.test(reference);
}

/* -------------------------------------------------------------------------- */
/* Verify                                                                      */
/* -------------------------------------------------------------------------- */

/**
 * Calls Paystack's transaction.verify endpoint.
 *
 * Docs: https://paystack.com/docs/api/transaction/#verify
 *
 * Returns the normalised verification data on success, or throws on any
 * non-success / untrusted response.
 */
export async function verifyPaystackTransaction(reference: string): Promise<PaystackVerificationData> {
  if (!isValidPaystackReference(reference)) {
    throw new Error("Invalid transaction reference format.");
  }

  const secret = getPaystackSecretKey();

  const response = await fetch(
    `https://api.paystack.co/transaction/verify/${encodeURIComponent(reference)}`,
    {
      method: "GET",
      headers: {
        Authorization: `Bearer ${secret}`,
        Accept: "application/json"
      },
      cache: "no-store"
    }
  );

  if (!response.ok) {
    const text = await response.text().catch(() => "");
    throw new Error(
      `Paystack verify HTTP ${response.status}: ${text || response.statusText}`
    );
  }

  const json = (await response.json()) as {
    status: boolean;
    message?: string;
    data?: Partial<PaystackVerificationData> & { status?: string };
  };

  // Paystack wraps the real verification in json.data.status === "success".
  if (!json.status || !json.data || json.data.status !== "success") {
    throw new Error(
      `Paystack transaction not successful: ${json.message ?? "unknown error"}`
    );
  }

  const data = json.data;
  const amount = typeof data.amount === "number" ? data.amount : Number(data.amount);

  return {
    status: true,
    amount,
    currency: data.currency ?? "GHS",
    reference: data.reference ?? reference,
    customer: {
      email: data.customer?.email ?? "",
      customer_code: data.customer?.customer_code
    },
    authorization: data.authorization,
    metadata: data.metadata
  };
}

