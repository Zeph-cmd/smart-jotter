/** Returns the expected prices (in major currency units) for a plan. */
function getPlanPrices(
  planType: "stt" | "ai" | "stt_topup",
  planId: PlanId | AiPlanId | SttTopupId
): { priceGhs: number; priceUsd: number } {
  if (planType === "stt") {
    const plan = SUBSCRIPTION_PLANS.find((p) => p.id === planId);
    if (!plan) {
      throw new Error(`Unknown Speech-to-Text plan: ${planId}`);
    }
    return { priceGhs: plan.priceGhs, priceUsd: plan.priceUsd };
  }

  if (planType === "stt_topup") {
    const plan = STT_TOPUP_PLANS.find((p) => p.id === planId);
    if (!plan) {
      throw new Error(`Unknown Speech-to-Text top-up: ${planId}`);
    }
    // Top-ups are GHS-only for now; no USD equivalent is offered.
    return { priceGhs: plan.priceGhs, priceUsd: plan.priceGhs };
  }

  const plan = AI_SUBSCRIPTION_PLANS.find((p) => p.id === planId);
  if (!plan) {
    throw new Error(`Unknown AI Writing Assist plan: ${planId}`);
  }
  return { priceGhs: plan.priceGhs, priceUsd: plan.priceUsd };
}

/**
 * Safely extracts and validates the plan metadata attached to the transaction.
 * Throws if the metadata is missing or references an unknown plan.
 */
export function extractMetadata(raw: unknown): PaystackMetadata {
  const meta = raw as Partial<PaystackMetadata> | undefined;

  if (!meta || typeof meta !== "object") {
    throw new Error("Transaction metadata is missing.");
  }

  const userId = meta.user_id;
  const planType = meta.plan_type;
  const planId = meta.plan_id;

  if (!userId || typeof userId !== "string") {
    throw new Error("Transaction metadata is missing user_id.");
  }

  if (!planId || typeof planId !== "string") {
    throw new Error("Transaction metadata is missing plan_id.");
  }

  if (planType !== "stt" && planType !== "ai" && planType !== "stt_topup") {
    throw new Error(`Invalid plan_type in metadata: ${String(planType)}`);
  }

  if (planType === "stt") {
    if (!SUBSCRIPTION_PLANS.some((p) => p.id === planId)) {
      throw new Error(`Invalid Speech-to-Text plan_id: ${String(planId)}`);
    }
  } else if (planType === "stt_topup") {
    if (!STT_TOPUP_PLANS.some((p) => p.id === planId)) {
      throw new Error(`Invalid Speech-to-Text top-up plan_id: ${String(planId)}`);
    }
  } else {
    if (!AI_SUBSCRIPTION_PLANS.some((p) => p.id === planId)) {
      throw new Error(`Invalid AI Writing Assist plan_id: ${String(planId)}`);
    }
  }

  return { user_id: userId, plan_type: planType, plan_id: planId };
}

/**
 * Confirms the verified transaction's amount matches the expected plan price
 * for its currency. African visitors are charged in GHS; visitors outside
 * Africa are charged in USD at the fixed rate in lib/config/plans.ts.
 * Paystack amounts are in the smallest currency unit (pesewas/cents), so
 * 50 GHS is returned as 5000 and 20 USD as 2000.
 */
export function assertAmountMatches(
  data: PaystackVerificationData,
  metadata: PaystackMetadata
) {
  const prices = getPlanPrices(metadata.plan_type, metadata.plan_id);
  const currency = data.currency.toUpperCase();

  if (currency !== "GHS" && currency !== "USD") {
    throw new Error(`Currency mismatch: paid in ${currency}, expected GHS or USD.`);
  }

  // Top-ups are GHS-only: reject any USD payment carrying a top-up id so a
  // forged metadata pair can never activate minutes at the wrong price.
  if (metadata.plan_type === "stt_topup" && currency !== "GHS") {
    throw new Error(
      `Currency mismatch: Extra Minutes are charged in GHS, paid in ${currency}.`
    );
  }

  const expectedMajor = currency === "USD" ? prices.priceUsd : prices.priceGhs;
  const expectedMinor = Math.round(expectedMajor * 100);

  if (data.amount !== expectedMinor) {
    throw new Error(
      `Amount mismatch: paid ${data.amount} minor units, expected ${expectedMinor} (${expectedMajor} ${currency}).`
    );
  }
}

/* -------------------------------------------------------------------------- */
/* Idempotency ledger (replay-attack defense)                                  */
/* -------------------------------------------------------------------------- */

/**
 * Records a processed transaction in `sj_paystack_transactions`.
 *
 * Returns `true` if this is a NEW transaction (caller should grant entitlements),
 * or `false` if the transaction was ALREADY processed (caller should skip the
 * grant but still return success to the client / Paystack).
 *
 * This closes a replay gap where the same valid reference could be submitted
 * repeatedly to keep refreshing subscription expiry dates without paying again.
 */
export async function isTransactionProcessed(
  supabase: ReturnType<typeof createServiceRoleSupabaseClient>,
  reference: string
): Promise<boolean> {
  const { data, error } = await supabase
    .from("sj_paystack_transactions")
    .select("reference")
    .eq("reference", reference)
    .maybeSingle();

  if (error) {
    // Fail closed: if we can't check the ledger, don't silently grant.
    throw new Error(`Ledger check failed: ${error.message}`);
  }

  return Boolean(data);
}

/**
 * Inserts the transaction into the ledger after a successful grant. Uses
 * `onConflict: "reference"` with no update to guarantee idempotency even
 * under concurrent verify + webhook delivery.
 */
export async function markTransactionProcessed(
  supabase: ReturnType<typeof createServiceRoleSupabaseClient>,
  reference: string,
  metadata: PaystackMetadata,
  amountMinor: number,
  currency: string
): Promise<void> {
  const { error } = await supabase
    .from("sj_paystack_transactions")
    .upsert(
      {
        reference,
        user_id: metadata.user_id,
        plan_type: metadata.plan_type,
        plan_id: metadata.plan_id,
        amount_minor: amountMinor,
        currency: currency.toUpperCase()
      },
      { onConflict: "reference", ignoreDuplicates: true }
    );

  if (error) {
    // Non-fatal: the grant already happened. Log but don't throw, since the
    // entitlements are already active.
    logServerError("paystack-ledger-insert", error);
  }
}

